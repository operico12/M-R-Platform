// pnpm seed:sql --admin you@example.com [--units 40] [--days 120] [--end ISO] > seed.sql
// pnpm seed:sql --components-only --days 30 --end ISO > components.sql   (adds the phase 3
//   component history to a demo site loaded earlier with the same --units, --days, --seed and --end)
// pnpm seed:sql --condition-only --days 30 --end ISO > condition.sql   (adds the oil analysis history
//   the same way; docs/condition-monitoring.md)
// pnpm seed:sql --rcm-only --days 30 --end ISO > rcm.sql   (adds the RCM failure mode library and
//   issued job plans; docs/rcm.md)
//
// Writes SQL that loads the synthetic fleet into a new Supabase project and
// invites the first Admin by email. Paste it into the Supabase SQL editor
// after the migrations. Synthetic data only (CLAUDE.md rule 9).

import { createHash } from 'node:crypto';
import { DEFAULT_FLAG_RULES } from '../config.js';
import { defaultReasonCodes } from '../console.js';
import { generateFleet } from './generate.js';

const args = process.argv.slice(2);
const opt = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const componentsOnly = args.includes('--components-only');
const conditionOnly = args.includes('--condition-only');
const rcmOnly = args.includes('--rcm-only');
const admin = opt('admin')?.trim().toLowerCase();
if (!componentsOnly && !conditionOnly && !rcmOnly && (!admin || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(admin))) {
  console.error('Usage: pnpm seed:sql --admin you@example.com > seed.sql');
  process.exit(1);
}
const ds = generateFleet({ units: Number(opt('units') ?? 40), days: Number(opt('days') ?? 120), seed: Number(opt('seed') ?? 42), end: opt('end') });

/** Same synthetic id → same uuid every time, so the file can be re-run safely. */
const uuid = (s: string) => {
  const h = createHash('sha1').update(`mr-demo:${s}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

const T = uuid('tenant');
const S = uuid('site');
const SHOP = uuid('shop');
const line = (id?: string) => (id ? uuid(`line:${id}`) : undefined);
const unit = (id: string) => uuid(`asset:${id}`);

const out: string[] = [];
out.push('-- Synthetic demo fleet for the M&R platform. Generated by pnpm seed:sql. No site data.');
out.push('begin;');
const flagId = new Map(ds.flags.map((f) => [f.id, uuid(`flag:${f.id}`)]));
if (!componentsOnly && !conditionOnly && !rcmOnly) {
out.push(`insert into tenants (id, name) values ('${T}', 'Demo tenant') on conflict do nothing;`);
out.push(`insert into sites (id, tenant_id, name, time_zone) values ('${S}', '${T}', ${lit(ds.site.name)}, ${lit(ds.site.timeZone)}) on conflict do nothing;`);
out.push(`insert into shift_calendars (tenant_id, site_id, shifts, rotation, effective_from) select '${T}', '${S}', ${q(ds.calendar.shifts)}, ${q(ds.calendar.rotation)}, '2020-01-01' where not exists (select 1 from shift_calendars where site_id = '${S}');`);
out.push(`insert into flag_rules (tenant_id, site_id, rules, effective_from) select '${T}', '${S}', ${q(DEFAULT_FLAG_RULES)}, '2020-01-01' where not exists (select 1 from flag_rules where site_id = '${S}');`);
out.push(`insert into shops (id, tenant_id, site_id, name) values ('${SHOP}', '${T}', '${S}', 'Truck shop') on conflict do nothing;`);
for (const [i, l] of ds.shopLines.entries()) {
  out.push(`insert into shop_lines (id, tenant_id, site_id, shop_id, number, name, line_type, capacity, sort_order) values ('${line(l.id)}', '${T}', '${S}', '${SHOP}', ${l.number ?? 'null'}, ${l.name ? lit(l.name) : 'null'}, ${lit(l.lineType)}, ${l.capacity}, ${i}) on conflict do nothing;`);
}
for (const c of ds.closures) {
  out.push(`insert into shop_line_closures (tenant_id, site_id, shop_line_id, starts_at, ends_at, reason) select '${T}', '${S}', '${line(c.lineId)}', '${c.start}', ${c.end ? `'${c.end}'` : 'null'}, ${lit(c.reason)} where not exists (select 1 from shop_line_closures where shop_line_id = '${line(c.lineId)}' and starts_at = '${c.start}');`);
}
for (const f of ds.fieldLocations) out.push(`insert into field_locations (tenant_id, site_id, name) select '${T}', '${S}', ${lit(f)} where not exists (select 1 from field_locations where site_id = '${S}' and name = ${lit(f)});`);

const assets = ds.assets.map((a) => ({ ...a, id: unit(a.id) }));
out.push(`select app_save_assets('${S}', ${q(assets)});`);
// Attributes apply from well before the history starts.
out.push(`update asset_attributes set effective_from = '2020-01-01' where site_id = '${S}' and effective_from > now() - interval '1 hour' and lifecycle = 'active';`);
// Lifecycle: the generator parks one unit part way through; the attribute row carries it.
for (const l of ds.lifecycle.filter((x) => x.status !== 'active')) {
  out.push(`update asset_attributes set effective_to = '${l.start}' where asset_id = '${unit(l.assetId)}' and effective_to is null;`);
  out.push(`insert into asset_attributes (tenant_id, site_id, asset_id, fleet_id, model, lifecycle, effective_from, effective_to) select tenant_id, site_id, asset_id, fleet_id, model, '${l.status}', '${l.start}', ${l.end ? `'${l.end}'` : 'null'} from asset_attributes where asset_id = '${unit(l.assetId)}' and effective_to = '${l.start}';`);
}

const flags = ds.flags.map((f) => ({
  ...f, id: flagId.get(f.id), siteId: S, unitId: unit(f.unitId), linkedFromFlagId: f.linkedFromFlagId ? flagId.get(f.linkedFromFlagId) : undefined,
  locations: f.locations.map((l) => ({ ...l, shopLineId: line(l.shopLineId) })),
}));
for (let i = 0; i < flags.length; i += 200) out.push(`select app_save_flags('${S}', ${q(flags.slice(i, i + 200))});`);

const smu = ds.smu.map((r) => ({ unitId: unit(r.unitId), at: r.at, hours: r.hours, source: 'synthetic' }));
for (let i = 0; i < smu.length; i += 2000) out.push(`select app_save_smu('${S}', ${q(smu.slice(i, i + 2000))});`);
const wos = ds.workOrders.map((w) => ({ ...w, id: uuid(`wo:${w.id}`), assetId: w.assetId ? unit(w.assetId) : undefined }));
for (let i = 0; i < wos.length; i += 500) out.push(`select app_save_work_orders('${S}', ${q(wos.slice(i, i + 500))});`);
out.push(`select app_save_codes('${S}', ${q(defaultReasonCodes().map((c) => ({ ...c, id: uuid(`code:${c.id}`) })))});`);

// First Admin: an invite that becomes a membership when this email signs in.
out.push(`insert into site_invites (tenant_id, site_id, email, name, role, scope) values ('${T}', '${S}', ${lit(admin!)}, 'Site admin', 'admin', '{*}') on conflict (site_id, email) do nothing;`);
}

// Phase 3: component history (docs/component-life.md). Written straight to the tables: the SQL
// editor is not a client, so the guards let it through, and who and when come from the history.
const SUP = uuid('user:supervisor');
const comp = (id: string) => uuid(`component:${id}`);
if (!conditionOnly && !rcmOnly) {
const comps = ds.components.map((c) => ({ id: comp(c.id), serial: c.serial, kind: c.kind, models: c.models, hoursAtEntry: c.hoursAtEntry, rebuildsAtEntry: c.rebuildsAtEntry, createdAt: c.createdAt }));
out.push(`insert into components (id, tenant_id, site_id, serial, kind, models, hours_at_entry, rebuilds_at_entry, created_by, created_at)
  select (x->>'id')::uuid, '${T}', '${S}', x->>'serial', x->>'kind', array(select jsonb_array_elements_text(x->'models')), (x->>'hoursAtEntry')::numeric, (x->>'rebuildsAtEntry')::int, '${SUP}', (x->>'createdAt')::timestamptz
  from jsonb_array_elements(${q(comps)}) x on conflict do nothing;`);
const evs = ds.componentEvents.map(({ enteredBy: _b, enteredAt: _a, ...e }) => ({ ...e, id: uuid(`cev:${e.id}`), componentId: comp(e.componentId), unitId: e.unitId ? unit(e.unitId) : undefined, flagId: e.flagId ? flagId.get(e.flagId) : undefined }));
for (let i = 0; i < evs.length; i += 1000) {
  out.push(`insert into component_events (id, tenant_id, site_id, component_id, kind, at, unit_id, position, smu, reason, flag_id, work_order, vendor, reference, received_as, warranty_hours, warranty_months, core_due_by, claim, note, entered_by, entered_at)
  select (x->>'id')::uuid, '${T}', '${S}', (x->>'componentId')::uuid, x->>'kind', (x->>'at')::timestamptz, (x->>'unitId')::uuid, x->>'position', (x->>'smu')::numeric, x->>'reason', (x->>'flagId')::uuid,
    x->>'workOrder', x->>'vendor', x->>'reference', x->>'receivedAs', (x->>'warrantyHours')::numeric, (x->>'warrantyMonths')::int, (x->>'coreDueBy')::date, x->>'claim', x->>'note', '${SUP}', (x->>'at')::timestamptz
  from jsonb_array_elements(${q(evs.slice(i, i + 1000))}) x on conflict do nothing;`);
}
const costs = evs.filter((e) => e.cost !== undefined).map((e) => ({ id: e.id, cost: e.cost, at: e.at }));
out.push(`insert into component_event_costs (event_id, tenant_id, site_id, cost, entered_by, entered_at)
  select (x->>'id')::uuid, '${T}', '${S}', (x->>'cost')::numeric, '${SUP}', (x->>'at')::timestamptz from jsonb_array_elements(${q(costs)}) x on conflict do nothing;`);
const lts = ds.lifeTargets.map((t) => ({ ...t, id: uuid(`life-target:${t.id}`) }));
out.push(`insert into life_targets (id, tenant_id, site_id, model, kind, hours, effective_from, reason, set_by, set_at)
  select (x->>'id')::uuid, '${T}', '${S}', x->>'model', x->>'kind', (x->>'hours')::int, (x->>'effectiveFrom')::date, x->>'reason', '${uuid('user:admin')}', (x->>'setAt')::timestamptz
  from jsonb_array_elements(${q(lts)}) x on conflict do nothing;`);
}

// Phase 3: oil analysis and responses (docs/condition-monitoring.md), written straight to the tables like
// the components above. 400 samples a statement keeps each well under the SQL editor's size limit.
const RE = uuid('user:reliability_engineer');
if (!componentsOnly && !rcmOnly) {
  const who = (id: string) => (id === 'demo-supervisor' ? SUP : RE);
  const samples = ds.oilSamples.map((x) => ({ ...x, id: uuid(`oil:${x.id}`), unitId: unit(x.unitId), by: who(x.enteredBy) }));
  for (let i = 0; i < samples.length; i += 400) {
    out.push(`insert into oil_samples (id, tenant_id, site_id, unit_id, compartment, taken_at, reported_at, smu, oil_hours, lab_ref, lab_severity, readings, comment, severity, reasons, entered_by, entered_at)
  select (x->>'id')::uuid, '${T}', '${S}', (x->>'unitId')::uuid, x->>'compartment', (x->>'takenAt')::timestamptz, (x->>'reportedAt')::timestamptz, (x->>'smu')::numeric, (x->>'oilHours')::numeric,
    x->>'labRef', x->>'labSeverity', x->'readings', x->>'comment', x->>'severity', x->'reasons', (x->>'by')::uuid, (x->>'enteredAt')::timestamptz
  from jsonb_array_elements(${q(samples.slice(i, i + 400))}) x on conflict do nothing;`);
  }
  const responses = ds.cmResponses.map((r) => ({ ...r, id: uuid(`cmr:${r.id}`), sampleId: uuid(`oil:${r.sampleId}`), by: who(r.by) }));
  out.push(`insert into cm_responses (id, tenant_id, site_id, sample_id, action, work_order, note, responded_by, responded_at)
  select (x->>'id')::uuid, '${T}', '${S}', (x->>'sampleId')::uuid, x->>'action', x->>'workOrder', x->>'note', (x->>'by')::uuid, (x->>'at')::timestamptz
  from jsonb_array_elements(${q(responses)}) x on conflict do nothing;`);
}
// Phase 3: RCM failure modes and issued job plans (docs/rcm.md). Every row is by the demo reliability engineer.
if (!componentsOnly && !conditionOnly) {
  const modeId = (id: string) => uuid(`rcm:${id}`);
  const modes = ds.rcmModes.map((m) => ({ ...m, id: uuid(`rcmrow:${m.id}`), modeId: modeId(m.modeId) }));
  out.push(`insert into rcm_modes (id, tenant_id, site_id, mode_id, revision, model, system, component, func, functional_failure, mode, effect, consequence, answers,
    recommended, task_type, override_reason, task, interval_hours, interval_basis, craft, people, task_hours, parts, change_note, created_by, created_at, retired_by, retired_at, retire_reason)
  select (x->>'id')::uuid, '${T}', '${S}', (x->>'modeId')::uuid, (x->>'revision')::int, x->>'model', x->>'system', x->>'component', x->>'func', x->>'functionalFailure', x->>'mode',
    x->>'effect', x->>'consequence', x->'answers', x->>'recommended', x->>'taskType', x->>'overrideReason', coalesce(x->>'task', ''), (x->>'intervalHours')::numeric, x->>'intervalBasis',
    x->>'craft', (x->>'people')::int, (x->>'taskHours')::numeric, x->'parts', x->>'changeNote', '${RE}', (x->>'createdAt')::timestamptz,
    case when x ? 'retiredAt' then '${RE}'::uuid end, (x->>'retiredAt')::timestamptz, x->>'retireReason'
  from jsonb_array_elements(${q(modes)}) x on conflict do nothing;`);
  const versions = ds.jobPlanVersions.map((v) => ({ ...v, id: uuid(`jpv:${v.id}`), content: { ...v.content, tasks: v.content.tasks.map((t) => ({ ...t, modeId: modeId(t.modeId) })) } }));
  out.push(`insert into job_plan_versions (id, tenant_id, site_id, jpnum, model, hours, revision, content, note, issued_by, issued_at)
  select (x->>'id')::uuid, '${T}', '${S}', x->>'jpnum', x->>'model', (x->>'hours')::numeric, (x->>'revision')::int, x->'content', x->>'note', '${RE}', (x->>'issuedAt')::timestamptz
  from jsonb_array_elements(${q(versions)}) x on conflict do nothing;`);
}
out.push('commit;');
out.push(rcmOnly ? '-- Done. Open RCM in the app to see the library and job plans.' : conditionOnly ? '-- Done. Open Condition in the app to see the board.' : componentsOnly ? '-- Done. Open Components in the app to see the board.' : `-- Done. Sign in to the app as ${admin} to become the site Admin, then invite others from Console > Users.`);
process.stdout.write(out.join('\n') + '\n');
