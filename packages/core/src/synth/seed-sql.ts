// pnpm seed:sql --admin you@example.com [--units 40] [--days 120] > seed.sql
//
// Writes SQL that loads the synthetic fleet into a new Supabase project and
// invites the first Admin by email. Paste it into the Supabase SQL editor
// after the migrations. Synthetic data only (CLAUDE.md rule 9).

import { createHash } from 'node:crypto';
import { DEFAULT_FLAG_RULES } from '../config.js';
import { defaultReasonCodes } from '../console.js';
import { generateFleet } from './generate.js';

const args = process.argv.slice(2);
const opt = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const admin = opt('admin')?.trim().toLowerCase();
if (!admin || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(admin)) {
  console.error('Usage: pnpm seed:sql --admin you@example.com > seed.sql');
  process.exit(1);
}
const ds = generateFleet({ units: Number(opt('units') ?? 40), days: Number(opt('days') ?? 120), seed: Number(opt('seed') ?? 42) });

/** Same synthetic id → same uuid every time, so the file can be re-run safely. */
const uuid = (s: string) => {
  const h = createHash('sha1').update(`mr-demo:${s}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

const T = uuid('tenant');
const S = uuid('site');
const SHOP = uuid('shop');
const line = (id?: string) => (id ? uuid(`line:${id}`) : undefined);
const unit = (id: string) => uuid(`asset:${id}`);

const out: string[] = [];
out.push('-- Synthetic demo fleet for the M&R platform. Generated by pnpm seed:sql. No site data.');
out.push('begin;');
out.push(`insert into tenants (id, name) values ('${T}', 'Demo tenant') on conflict do nothing;`);
out.push(`insert into sites (id, tenant_id, name, time_zone) values ('${S}', '${T}', ${lit(ds.site.name)}, ${lit(ds.site.timeZone)}) on conflict do nothing;`);
out.push(`insert into shift_calendars (tenant_id, site_id, shifts, rotation, effective_from) select '${T}', '${S}', ${q(ds.calendar.shifts)}, ${q(ds.calendar.rotation)}, '2020-01-01' where not exists (select 1 from shift_calendars where site_id = '${S}');`);
out.push(`insert into flag_rules (tenant_id, site_id, rules, effective_from) select '${T}', '${S}', ${q(DEFAULT_FLAG_RULES)}, '2020-01-01' where not exists (select 1 from flag_rules where site_id = '${S}');`);
out.push(`insert into shops (id, tenant_id, site_id, name) values ('${SHOP}', '${T}', '${S}', 'Truck shop') on conflict do nothing;`);
for (const [i, l] of ds.shopLines.entries()) {
  out.push(`insert into shop_lines (id, tenant_id, site_id, shop_id, number, name, line_type, capacity, sort_order) values ('${line(l.id)}', '${T}', '${S}', '${SHOP}', ${l.number ?? 'null'}, ${l.name ? lit(l.name) : 'null'}, ${lit(l.lineType)}, ${l.capacity}, ${i}) on conflict do nothing;`);
}
for (const c of ds.closures) {
  out.push(`insert into shop_line_closures (tenant_id, site_id, shop_line_id, starts_at, ends_at, reason) select '${T}', '${S}', '${line(c.lineId)}', '${c.start}', ${c.end ? `'${c.end}'` : 'null'}, ${lit(c.reason)} where not exists (select 1 from shop_line_closures where shop_line_id = '${line(c.lineId)}' and starts_at = '${c.start}');`);
}
for (const f of ds.fieldLocations) out.push(`insert into field_locations (tenant_id, site_id, name) select '${T}', '${S}', ${lit(f)} where not exists (select 1 from field_locations where site_id = '${S}' and name = ${lit(f)});`);

const assets = ds.assets.map((a) => ({ ...a, id: unit(a.id) }));
out.push(`select app_save_assets('${S}', ${q(assets)});`);
// Attributes apply from well before the history starts.
out.push(`update asset_attributes set effective_from = '2020-01-01' where site_id = '${S}' and effective_from > now() - interval '1 hour' and lifecycle = 'active';`);
// Lifecycle: the generator parks one unit part way through; the attribute row carries it.
for (const l of ds.lifecycle.filter((x) => x.status !== 'active')) {
  out.push(`update asset_attributes set effective_to = '${l.start}' where asset_id = '${unit(l.assetId)}' and effective_to is null;`);
  out.push(`insert into asset_attributes (tenant_id, site_id, asset_id, fleet_id, model, lifecycle, effective_from, effective_to) select tenant_id, site_id, asset_id, fleet_id, model, '${l.status}', '${l.start}', ${l.end ? `'${l.end}'` : 'null'} from asset_attributes where asset_id = '${unit(l.assetId)}' and effective_to = '${l.start}';`);
}

const flagId = new Map(ds.flags.map((f) => [f.id, uuid(`flag:${f.id}`)]));
const flags = ds.flags.map((f) => ({
  ...f, id: flagId.get(f.id), siteId: S, unitId: unit(f.unitId), linkedFromFlagId: f.linkedFromFlagId ? flagId.get(f.linkedFromFlagId) : undefined,
  locations: f.locations.map((l) => ({ ...l, shopLineId: line(l.shopLineId) })),
}));
for (let i = 0; i < flags.length; i += 200) out.push(`select app_save_flags('${S}', ${q(flags.slice(i, i + 200))});`);

const smu = ds.smu.map((r) => ({ unitId: unit(r.unitId), at: r.at, hours: r.hours, source: 'synthetic' }));
for (let i = 0; i < smu.length; i += 2000) out.push(`select app_save_smu('${S}', ${q(smu.slice(i, i + 2000))});`);
const wos = ds.workOrders.map((w) => ({ ...w, id: uuid(`wo:${w.id}`), assetId: w.assetId ? unit(w.assetId) : undefined }));
for (let i = 0; i < wos.length; i += 500) out.push(`select app_save_work_orders('${S}', ${q(wos.slice(i, i + 500))});`);
out.push(`select app_save_codes('${S}', ${q(defaultReasonCodes().map((c) => ({ ...c, id: uuid(`code:${c.id}`) })))});`);

// First Admin: an invite that becomes a membership when this email signs in.
out.push(`insert into site_invites (tenant_id, site_id, email, name, role, scope) values ('${T}', '${S}', ${lit(admin)}, 'Site admin', 'admin', '{*}') on conflict (site_id, email) do nothing;`);
out.push('commit;');
out.push(`-- Done. Sign in to the app as ${admin} to become the site Admin, then invite others from Console > Users.`);
process.stdout.write(out.join('\n') + '\n');
